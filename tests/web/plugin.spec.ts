test('radar editors save signed emotion values, cancel drafts, and preserve the overview until save', async ({ page }) => {
  await open(page); await panel(page)
  const version = await page.locator('.mood-chart-card .mood-tag').textContent()
  const openEditor = async () => {
    await page.getByRole('button', { name: '编辑情绪', exact: true }).click()
    await expect(page.getByRole('dialog', { name: '编辑情绪' })).toBeVisible()
    await expect(page.getByRole('slider')).toHaveCount(5)
  }
  await openEditor()
  await expect(page.getByRole('button', { name: '保存情绪' })).toBeDisabled()
  await page.getByRole('spinbutton', { name: '悲喜数值', exact: true }).fill('-40.5')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.mood-chart-card .mood-tag')).toHaveText(version!)
  await openEditor()
  await expect(page.getByRole('button', { name: '保存情绪' })).toBeDisabled()
  await page.getByRole('spinbutton', { name: '悲喜数值', exact: true }).fill('-40.5')
  const anger = page.getByRole('spinbutton', { name: '愤怒数值', exact: true })
  await anger.fill('-1')
  expect(await anger.evaluate((el: HTMLInputElement) => el.validity.valid)).toBe(false)
  await anger.fill('20')
  await page.getByRole('button', { name: '保存情绪' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.mood-notice')).toContainText('情绪已保存')
  await expect(page.locator('.mood-history-item').first()).toContainText('用户手动修改情绪')
  const ratio = Number(await page.locator('g[data-axis="valence"] .mood-radar-value').getAttribute('data-ratio'))
  expect(ratio).toBeCloseTo(0.2975, 3)
  await page.reload(); await panel(page)
  expect(Number(await page.getByRole('meter', { name: '悲喜', exact: true }).getAttribute('aria-valuenow'))).toBeCloseTo(-40.5, 1)
})

test('neutral personality reacts across all five emotions, shows fractions and explains unchanged events', async ({ page }) => {
  await open(page); await panel(page)
  await page.getByRole('button', { name: '编辑性格', exact: true }).click()
  for (const name of ['社交取向', '探索取向', '立场坚持', '亲密距离', '结果预期', '敏感度', '恢复能力']) {
    await setSlider(page, name, 0)
  }
  await page.getByRole('button', { name: '保存性格' }).click()
  await expect(page.locator('.mood-notice')).toContainText('已保存')
  await page.getByRole('button', { name: '编辑情绪', exact: true }).click()
  for (const name of ['悲喜', '好恶', '愤怒', '恐惧／焦虑', '惊讶']) await page.getByRole('spinbutton', { name: `${name}数值`, exact: true }).fill('0')
  if (await page.getByRole('button', { name: '保存情绪' }).isEnabled()) await page.getByRole('button', { name: '保存情绪' }).click()
  else await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('meter', { name: '悲喜', exact: true })).toHaveAttribute('aria-valuenow', '0')
  const cases = [
    ['neutral-happy', '悲喜', 0.8, '0.8'], ['neutral-like', '好恶', 1, '1'],
    ['neutral-sad', '悲喜', -2, ''], ['neutral-anger', '愤怒', 2, ''],
    ['neutral-fear', '恐惧／焦虑', 2, ''], ['neutral-surprise', '惊讶', 2, ''],
  ] as const
  for (const [scenario, name, expected, displayed] of cases) {
    const before = Number(await page.getByRole('meter', { name, exact: true }).getAttribute('aria-valuenow'))
    await page.getByRole('button', { name: '返回对话' }).click()
    await newChat(page)
    await send(page, scenario)
    await expect(page.getByText('收到，我们继续。', { exact: true })).toBeVisible()
    await panel(page)
    const latest = page.locator('.mood-history-item').first()
    await expect(latest).toContainText(scenario)
    const after = Number(await page.getByRole('meter', { name, exact: true }).getAttribute('aria-valuenow'))
    expect(after - before).toBeCloseTo(expected, 1)
    if (displayed) await expect(page.getByLabel(`${name}值`, { exact: true })).toContainText(displayed)
  }
  await page.getByRole('button', { name: '返回对话' }).click()
  await newChat(page); await send(page, 'neutral-none')
  await expect(page.getByText('收到，我们继续。', { exact: true })).toBeVisible()
  await panel(page)
  await expect(page.locator('.mood-history-item').first()).toContainText('数值未变化：所有特征的程度均为 none')
})

